"""Generate the synthetic merchant dataset.

Seeded, so the demo never shifts under you: re-running this produces byte-identical output.
All data is synthetic and must be labelled as such in the UI.

    python scripts/gen_data.py

Shape we are aiming for (and assert at the end):
  * 90 days, mean settlement in [5800, 6200] so the burden tile reads 11.7% for a ₹700 debit
  * a mild weekday cycle, because real retail has one
  * a few genuinely closed days (₹0) and some washout days, the auto-debit still fires on
    those, which is what makes "shortfall days" a real number rather than always zero
  * a slump across the final week, so the coach alert fires on the same dataset
"""

from __future__ import annotations

import json
import random
from datetime import date, timedelta
from pathlib import Path

SEED = 42
DAYS = 90

# The 90-day mean we calibrate to. 700 / 6000 = 11.7%, which is the number on slide 6 of the
# deck - so the demo and the pitch agree to the decimal. BASE is solved for, not guessed.
TARGET_MEAN = 6000.0

# Mon..Sun. A kirana store is busier at the weekend and dead on Tuesday.
WEEKDAY_FACTOR = [0.97, 0.92, 0.98, 1.00, 1.08, 1.18, 1.05]

# Days counted back from the end: shop shut, or a washout.
CLOSED_DAYS = {61, 44, 23, 9}                 # ₹0 settlement
WASHOUT_DAYS = {52: 1800.0, 17: 900.0, 6: 1300.0}   # rain / local disruption

SLUMP_DAYS = 7          # the trailing dip the coach must catch
SLUMP_FACTOR = 0.68

OUT = Path(__file__).resolve().parent.parent / "data" / "demo.json"


def build_settlements(base: float) -> list[float]:
    rng = random.Random(SEED)
    today = date(2026, 10, 30)
    start = today - timedelta(days=DAYS - 1)

    rows: list[float] = []
    for i in range(DAYS):
        day = start + timedelta(days=i)
        back = DAYS - 1 - i          # 0 == most recent day

        if back in CLOSED_DAYS:
            rows.append(0.0)
            continue
        if back in WASHOUT_DAYS:
            rows.append(WASHOUT_DAYS[back])
            continue

        amount = base * WEEKDAY_FACTOR[day.weekday()]
        amount *= rng.uniform(0.90, 1.10)
        if back < SLUMP_DAYS:
            amount *= SLUMP_FACTOR

        rows.append(float(round(amount, -1)))    # nearest ₹10, like a real settlement
    return rows


def calibrated_settlements() -> list[float]:
    """Solve for the `base` that puts the 90-day mean on TARGET_MEAN.

    Closed and washout days are fixed rupee amounts that do not scale with `base`, so the
    mean is affine rather than proportional in `base` - hence a short fixed-point loop rather
    than a single multiply. Deterministic: the RNG is re-seeded on every call.
    """
    base = TARGET_MEAN
    rows = build_settlements(base)
    for _ in range(40):
        mean = sum(rows) / len(rows)
        if abs(mean - TARGET_MEAN) < 0.5:
            break
        base *= TARGET_MEAN / mean
        rows = build_settlements(base)
    return rows


def build_payload() -> dict:
    settlements = calibrated_settlements()
    today = date(2026, 10, 30)
    start = today - timedelta(days=DAYS - 1)

