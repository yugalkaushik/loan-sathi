def main() -> None:
    payload = build_payload()
    daily = payload["settlements"]["daily"]

    mean = sum(daily) / len(daily)
    last7 = sum(daily[-7:]) / 7
    installment = payload["offer"]["daily_installment"]

    # Calibration guards. If these trip, fix the GENERATOR constants above - never the engine.
    assert len(daily) == DAYS, f"expected {DAYS} days, got {len(daily)}"
    assert abs(mean - TARGET_MEAN) < 1.0, f"mean {mean:.1f} missed TARGET_MEAN {TARGET_MEAN}"
    # The three figures on deck slide 6 must come out of this dataset exactly.
    for shock, expected in ((0.0, 11.7), (-0.30, 16.7), (-0.50, 23.3)):
        got = round(installment / (mean * (1 + shock)) * 100, 1)
        assert got == expected, f"burden at {shock:+.0%} is {got}%, deck slide 6 says {expected}%"
    assert last7 < 0.80 * mean, f"trailing week {last7:.0f} is not a dip vs {mean:.0f} - coach would not fire"
    assert any(d < installment for d in daily[-30:]), "no shortfall days in the last 30 - that metric would read zero"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # Plain "Rs" in console output: the Windows console codepage (cp1252) cannot encode the
    # rupee sign and would raise UnicodeEncodeError. The JSON file itself is UTF-8 and uses the symbol.
    print(f"wrote {OUT}")
    print(f"  90-day mean      Rs {mean:,.0f}")
    print(f"  trailing 7-day   Rs {last7:,.0f}  ({(1 - last7 / mean) * 100:.1f}% below baseline)")
    print(f"  burden @   0%    {installment / mean * 100:.1f}%")
    print(f"  burden @ -30%    {installment / (mean * 0.7) * 100:.1f}%")
    print(f"  burden @ -50%    {installment / (mean * 0.5) * 100:.1f}%")
    print(f"  days below Rs {installment}: {sum(1 for d in daily if d < installment)} of 90")


if __name__ == "__main__":
    main()
